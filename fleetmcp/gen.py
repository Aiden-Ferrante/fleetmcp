"""Render generated.py from tools.yaml + fixtures/<app>.json (the apps' OpenAPI).

    python3 -m fleetmcp.gen            # from the repo root, rewrites fleetmcp/generated.py
    python3 -m fleetmcp.gen --check    # exit 1 if generated.py is stale (the test)
    python3 -m fleetmcp.gen --fetch    # refresh fixtures from the running apps first

Why generate rather than call the schema at runtime: the server must start with
no app up (a dead shipyard is a ToolError on the call, not a failure to list
tools), the tool set is curated not discovered, and a committed generated.py is
reviewable in a diff. Why not hand-write: the parameter names, types and body
fields are the apps' to change, and a generator re-run catches the change.

The schema supplies: path params, query params (name, type, required, default),
and the request body's fields via `$ref` into components.schemas. tools.yaml
supplies the words. Destructive tools gain `impact_token: str`, sent
as the app's own `?token=` query param (which is dropped from the signature).
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
TOOLS = HERE / "tools.yaml"
FIXTURES = HERE / "fixtures"
OUT = HERE / "generated.py"

PY = {"string": "str", "integer": "int", "number": "float", "boolean": "bool",
      "object": "dict", "array": "list"}


def _pytype(schema: dict) -> str:
    if not schema:
        return "str"
    if "$ref" in schema:
        return "dict"
    if "anyOf" in schema:
        kinds = [_pytype(s) for s in schema["anyOf"] if s.get("type") != "null"]
        return kinds[0] if len(kinds) == 1 else "str"
    return PY.get(schema.get("type", "string"), "str")


def _body_fields(op: dict, spec: dict) -> list[dict]:
    rb = op.get("requestBody")
    if not rb:
        return []
    schema = rb["content"]["application/json"]["schema"]
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        schema = spec["components"]["schemas"][name]
    if schema.get("type") != "object" and "properties" not in schema:
        return [{"name": "body", "type": "dict", "required": True, "raw": True}]
    req = set(schema.get("required", []))
    out = []
    for fname, fs in schema.get("properties", {}).items():
        out.append({"name": fname, "type": _pytype(fs), "required": fname in req,
                    "default": fs.get("default")})
    return out


def _params(op: dict) -> list[dict]:
    out = []
    for p in op.get("parameters", []):
        sch = p.get("schema", {})
        out.append({"name": p["name"], "where": p["in"], "type": _pytype(sch),
                    "required": p.get("required", False) or p["in"] == "path",
                    "default": sch.get("default")})
    return out


def _ident(name: str) -> str:
    n = re.sub(r"\W", "_", name)
    return n + "_" if n in {"from", "import", "class", "def", "return", "in", "is", "not"} else n


def render(tools_yaml: Path = TOOLS, fixtures: Path = FIXTURES) -> str:
    cfg = yaml.safe_load(tools_yaml.read_text())
    specs = {app: json.loads((fixtures / f"{app}.json").read_text()) for app in cfg["apps"]}
    lines = [
        '"""GENERATED by fleetmcp/gen.py from tools.yaml + fixtures/*.json — do not edit.',
        "",
        "Each function is one fleet tool: its signature comes from the app's OpenAPI",
        "schema, its docstring from tools.yaml. `python -m fleetmcp.gen` re-renders;",
        "tests/test_mcp.py fails when this file is stale.",
        '"""',
        "from __future__ import annotations",
        "",
        "import os",
        "",
        "from . import http as _http",
        "",
        "APPS = {",
    ]
    for app, a in cfg["apps"].items():
        lines.append(f'    {app!r}: (os.environ.get({a["url_env"]!r}) or {a["default"]!r}),')
    lines += ["}", "", "TOOLS: list[dict] = []", ""]

    for t in cfg["tools"]:
        spec = specs[t["app"]]
        op = spec["paths"].get(t["path"], {}).get(t["method"].lower())
        if op is None:
            raise SystemExit(f"{t['name']}: {t['method']} {t['path']} is not in fixtures/{t['app']}.json — refresh fixtures or fix tools.yaml")
        params = _params(op)
        if t["kind"] == "destructive":
            # The app's own `token` query param IS the impact token. Keep it out of
            # the signature, or the call dict gets `'token'` twice and one value is
            # silently dropped (the v0.1 bug: generated.py rendered
            # {'token': token, 'token': impact_token}).
            if not any(p["name"] == "token" and p["where"] == "query" for p in params):
                raise SystemExit(f"{t['name']}: destructive but {t['method']} {t['path']} takes no ?token= in fixtures/{t['app']}.json")
            params = [p for p in params if not (p["name"] == "token" and p["where"] == "query")]
        body = _body_fields(op, spec)
        args_req, args_opt = [], []
        for p in params:
            (args_req if p["required"] else args_opt).append(p)
        for b in body:
            (args_req if b["required"] else args_opt).append({**b, "where": "body"})
        sig = [f"{_ident(p['name'])}: {p['type']}" for p in args_req]
        if t["kind"] == "destructive":
            sig.append("impact_token: str")
        for p in args_opt:
            d = p.get("default")
            sig.append(f"{_ident(p['name'])}: {p['type']} | None = {d!r}" if d is not None else f"{_ident(p['name'])}: {p['type']} | None = None")
        path_expr = t["path"]
        for p in params:
            if p["where"] == "path":
                path_expr = path_expr.replace("{" + p["name"] + "}", "{" + _ident(p["name"]) + "}")
        q = ", ".join(f"{p['name']!r}: {_ident(p['name'])}" for p in params if p["where"] == "query")
        if t["kind"] == "destructive":
            q = (q + ", " if q else "") + "'token': impact_token"
        if body and body[0].get("raw"):
            b = "body"
        else:
            b = "{" + ", ".join(f"{f['name']!r}: {_ident(f['name'])}" for f in body) + "}" if body else "None"
        doc = t["description"].strip().replace('"""', "'''")
        lines += [
            f"def {t['name']}({', '.join(sig)}):",
            f'    """{doc}',
            "",
            f"    kind: {t['kind']} · {t['method']} {t['path']} on {t['app']}",
            '    """',
            f"    return _http.call(APPS[{t['app']!r}], {t['app']!r}, {t['method']!r}, f{path_expr!r},",
            f"                      params={{{q}}}, body={b})",
            "",
            "",
            f"TOOLS.append({{'name': {t['name']!r}, 'kind': {t['kind']!r}, 'app': {t['app']!r}, 'fn': {t['name']}}})",
            "",
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def fetch(fixtures: Path = FIXTURES) -> None:
    import httpx
    cfg = yaml.safe_load(TOOLS.read_text())
    for app, a in cfg["apps"].items():
        base = os.environ.get(a["url_env"]) or a["default"]  # the env wins, as it does at runtime
        r = httpx.get(base.rstrip("/") + "/openapi.json", timeout=10)
        r.raise_for_status()
        (fixtures / f"{app}.json").write_text(json.dumps(r.json(), indent=1, sort_keys=True) + "\n")
        print(f"fetched {app}: {len(r.json()['paths'])} paths")


def main(argv: list[str]) -> int:
    if "--fetch" in argv:
        fetch()
    text = render()
    if "--check" in argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print("generated.py is stale — run: python -m fleetmcp.gen", file=sys.stderr)
            return 1
        print("generated.py is current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(HERE.parent)} ({text.count('def ')} tools)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
